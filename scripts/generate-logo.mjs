// Converts brand/logo.svg into src/shared/ui/Logo/logoArt.tsx without touching any path data.
// Run it with `npm run logo:generate` after the brand logo changes.
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = new URL('../../../brand/logo.svg', import.meta.url);
const TARGET = new URL('../src/shared/ui/Logo/logoArt.tsx', import.meta.url);

const svg = readFileSync(SOURCE, 'utf8');

const viewBox = /viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"/.exec(svg);
const rootFill = /<svg[^>]*\sfill="([^"]+)"/.exec(svg);
if (!viewBox || !rootFill) throw new Error('logo.svg needs a "0 0 W H" viewBox and a root fill');
const [, width, height] = viewBox;

const inner = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>')).trim();

const toCamelCase = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

const jsx = inner
  // Ids are made unique per rendered logo, so the file's fixed ids become props.
  .replaceAll('url(#all575-logo-clip)', '__CLIP__')
  .replaceAll('url(#all575-logo-rainbow)', '__RAINBOW__')
  .replace(/\sid="all575-logo-clip"/g, ' id={clipId}')
  .replace(/\sid="all575-logo-rainbow"/g, ' id={rainbowId}')
  .replace(/="__CLIP__"/g, '={`url(#${clipId})`}')
  .replace(/="__RAINBOW__"/g, '={`url(#${rainbowId})`}')
  // Hyphenated SVG attributes (clip-path, stop-color, ...) are camelCase in JSX.
  .replace(/(\s)([a-z]+(?:-[a-z]+)+)=/g, (_, space, name) => `${space}${toCamelCase(name)}=`);

if (/\sid="/.test(jsx) || jsx.includes('all575-logo')) {
  throw new Error('logo.svg has an id or reference this script does not know how to replace');
}

const output = `// Generated by scripts/generate-logo.mjs from brand/logo.svg. Do not edit by hand.
import type { ComponentProps } from 'react';

export const LOGO_WIDTH = ${width};
export const LOGO_HEIGHT = ${height};

type LogoArtProps = ComponentProps<'svg'> & {
  rainbowId: string;
  clipId: string;
};

export function LogoArt({ rainbowId, clipId, ...svgProps }: LogoArtProps) {
  return (
    <svg viewBox="0 0 ${width} ${height}" fill="${rootFill[1]}" {...svgProps}>
${jsx}
    </svg>
  );
}
`;

writeFileSync(TARGET, output);
